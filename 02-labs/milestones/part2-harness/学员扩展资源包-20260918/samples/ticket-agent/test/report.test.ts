import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ageHours, isOverdue } from '../src/sla.ts';
import { searchTickets } from '../src/search.ts';
import { buildReport } from '../src/report.ts';
import type { Ticket, Policy, Query } from '../src/types.ts';
const {tickets,policy,now}: {tickets:Ticket[];policy:Policy;now:string}=JSON.parse(readFileSync(new URL('../sample.json',import.meta.url),'utf8'));
const ids=(q:Query)=>searchTickets(tickets,q,now,policy).map(x=>x.id);
test('UTC age',()=>assert.equal(ageHours(tickets[0],now),5));
test('offset age',()=>assert.equal(ageHours(tickets[3],now),10));
test('future clamp',()=>assert.equal(ageHours(tickets[5],now),0));
test('bad created date rejected',()=>assert.throws(()=>ageHours({...tickets[0],createdAt:'bad'},now),RangeError));
test('bad now rejected',()=>assert.throws(()=>ageHours(tickets[0],'bad'),RangeError));
test('urgent overdue',()=>assert.equal(isOverdue(tickets[0],now,policy),true));
test('normal overdue',()=>assert.equal(isOverdue(tickets[1],now,policy),true));
test('closed never overdue',()=>assert.equal(isOverdue(tickets[2],now,policy),false));
test('exact deadline not overdue',()=>assert.equal(isOverdue(tickets[4],now,policy),false));
test('policy is configurable',()=>assert.equal(isOverdue(tickets[0],now,{urgentHours:6,normalHours:24}),false));
test('memory sort: urgent first then createdAt then id',()=>assert.deepEqual(ids({}),['T03','T01','T05','T02','T04','T06']));
test('keyword case trim',()=>assert.deepEqual(ids({keyword:' api '}),['T01','T05','T04']));
test('team exact',()=>assert.deepEqual(ids({team:'平台'}),['T03','T01','T04','T06']));
test('closed filter',()=>assert.deepEqual(ids({status:'closed'}),['T03']));
test('all criteria AND',()=>assert.deepEqual(ids({keyword:'api',team:'平台',status:'open',overdueOnly:true}),['T01']));
test('overdue only',()=>assert.deepEqual(ids({overdueOnly:true}),['T01','T02']));
test('empty keyword',()=>assert.equal(ids({keyword:'   '}).length,6));
test('no match',()=>assert.deepEqual(ids({keyword:'不存在'}),[]));
test('empty data',()=>assert.deepEqual(searchTickets([],{},now,policy),[]));
test('tie breaker id',()=>{const a={...tickets[0],id:'B'},b={...tickets[0],id:'A'};assert.deepEqual(searchTickets([a,b],{},now,policy).map(x=>x.id),['A','B']);});
test('immutable input',()=>{const ts=tickets.map(x=>Object.freeze({...x}));Object.freeze(ts);const before=JSON.stringify(ts);searchTickets(ts as Ticket[],{},now,policy);assert.equal(JSON.stringify(ts),before);});
test('open report summary',()=>{const r=buildReport(tickets,{status:'open'},now,policy);assert.equal(r.total,5);assert.equal(r.overdue,2);assert.deepEqual(r.byTeam,{'平台':3,'前端':2});});
test('filtered report summary',()=>{const r=buildReport(tickets,{overdueOnly:true},now,policy);assert.equal(r.total,2);assert.deepEqual(r.byTeam,{'平台':1,'前端':1});});
test('empty summary',()=>assert.deepEqual(buildReport([],{},now,policy),{total:0,overdue:0,byTeam:{},rows:[]}));
